"""v18.14: words per sitting (the new translation where there is one), so the reading pace can plan and project the
finish date without downloading any book. Writes source/public/renaissance-books-words.js."""
import glob, json, os
HERE = os.path.dirname(os.path.abspath(__file__))
B = os.path.join(HERE, "..", "..", "source", "public", "books")
out = {}
for f in sorted(glob.glob(os.path.join(B, "*.json"))):
    name = os.path.basename(f)
    if name.endswith(".fresh.json"):
        continue
    bid = name[:-5]
    b = json.load(open(f, encoding="utf-8"))
    if "sittings" not in b:
        continue
    w = [s.get("words", 0) for s in b["sittings"]]
    fp = os.path.join(B, bid + ".fresh.json")
    if os.path.exists(fp):
        fr = json.load(open(fp, encoding="utf-8"))["sittings"]
        for n, s in fr.items():
            if 0 < int(n) <= len(w):
                w[int(n) - 1] = s["words"]
    out[bid] = w
js = "/* generated by scripts/library/build_words.py: words per sitting, for the reading pace */\nwindow.RN_BOOK_WORDS = " + json.dumps(out, separators=(",", ":")) + ";\n"
open(os.path.join(HERE, "..", "..", "source", "public", "renaissance-books-words.js"), "w").write(js)
print({k: len(v) for k, v in out.items()})
